"""Regenerate instr_rom.v (gate-level instruction ROM) from ../ROM.sv.

Usage:  python gen_rom.py [ROM.sv] [instr_rom.v]

Run it again whenever the program in ROM.sv changes. Only the words ROM.sv
initialises get a word line; every other address reads 0x0000, which decodes
as `add r0 = r0 + r0` -- a no-op (r0 is never written).
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'ROM.sv')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'instr_rom.v')

# ---- read the program: registan[N] = 16'hXXXX;  // comment --------------------
words = {}
for line in open(src):
    code, _, note = line.partition('//')
    m = re.search(r"registan\s*\[\s*(\d+)\s*\]\s*=\s*16'h([0-9a-fA-F_]+)", code)
    if m:
        addr, val = int(m.group(1)), int(m.group(2).replace('_', ''), 16)
        if addr > 127:
            sys.exit(f'{src}: address {addr} is outside the 128-word ROM')
        words[addr] = (val, ' '.join(note.split()))
if not words:
    sys.exit(f'{src}: no registan[N] = 16\'h.... lines found')
addrs = sorted(words)


def bits(v):
    s = f'{v:016b}'
    return ' '.join(s[i:i + 4] for i in range(0, 16, 4))


# ---- header -------------------------------------------------------------------
rule = '// ' + '=' * 77 + '\n'
out = rule
out += '// instr_rom.v -- instruction ROM, gate level (equivalent of ROM.sv, module `ROME`)\n'
out += '//\n'
out += '// GENERATED by gen_rom.py from ROM.sv -- edit ROM.sv and re-run, do not hand-edit.\n'
out += '//\n'
out += '// A ROM is an address decoder plus an OR plane:\n'
out += '//   1) PC[3:0] -> dec4to16_en (lo), PC[6:4] -> dec3to8_en (hi)   (PC[15:7] unused)\n'
out += '//   2) word line  wl<k> = lo[k%16] & hi[k/16]  -- 1 when PC[6:0] == k\n'
out += '//   3) bit line   IR[b] = OR of the word lines whose word has bit b = 1\n'
out += '// Uninitialised addresses read 0x0000 (no word line fires) = a no-op.\n'
out += '//\n'
out += '// In Virtuoso the OR plane can also be drawn as a NOR-ROM transistor matrix:\n'
out += '// one row per word line, one column per IR bit, a transistor wherever the\n'
out += '// table below has a 1.\n'
out += '//\n'
out += '//   word  hex    IR[15:0]              program (comment from ROM.sv)\n'
for k in addrs:
    v, note = words[k]
    out += f'//   {k:4d}  {v:04X}   {bits(v)}   {note}'.rstrip() + '\n'
out += rule

# ---- body -------------------------------------------------------------------
out += 'module instr_rom (input [15:0] PC, output [15:0] IR);\n'
out += '  wire [15:0] lo;\n'
out += '  wire [7:0]  hi;\n'
wl = [f'wl{k}' for k in addrs]
for i in range(0, len(wl), 10):
    out += '  wire ' + ', '.join(wl[i:i + 10]) + ';\n'

out += "\n  // ---- address decode ------------------------------------------------------------\n"
out += "  dec4to16_en u_dlo (.a(PC[3:0]), .en(1'b1), .y(lo));\n"
out += "  dec3to8_en  u_dhi (.a(PC[6:4]), .en(1'b1), .y(hi));\n"

out += "\n  // ---- word lines ------------------------------------------------------------------\n"
nw = max(len(f'u_wl{k}') for k in addrs)
for k in addrs:
    v, note = words[k]
    pins = f'(.A(lo[{k % 16}]),'.ljust(13) + f' .B(hi[{k // 16}]),' + f' .Y(wl{k}));'.ljust(12)
    out += f'  AND2 {f"u_wl{k}":<{nw}} {pins}  // {v:04X}  {note}'.rstrip() + '\n'

out += "\n  // ---- bit lines: IR[b] = OR of word lines (balanced OR2 tree) -----------------------\n"
for b in range(15, -1, -1):
    ones = [f'wl{k}' for k in addrs if (words[k][0] >> b) & 1]
    out += f'  // IR[{b}] = ' + (' | '.join(ones) if ones else "0 (GND)") + '\n'
    if not ones:
        out += f"  assign IR[{b}] = 1'b0;\n"
        continue
    if len(ones) == 1:
        out += f'  assign IR[{b}] = {ones[0]};\n'
        continue
    level, nets, decl, gates = 1, ones, [], []
    while len(nets) > 1:
        nxt = []
        for i in range(0, len(nets) - 1, 2):
            y = f'IR[{b}]' if len(nets) == 2 else f'ir{b}_{level}_{i // 2}'
            if len(nets) != 2:
                decl.append(y)
            gates.append((f'u_ir{b}_{level}_{i // 2}', nets[i], nets[i + 1], y))
            nxt.append(y)
        if len(nets) % 2:
            nxt.append(nets[-1])
        nets, level = nxt, level + 1
    for i in range(0, len(decl), 8):
        out += '  wire ' + ', '.join(decl[i:i + 8]) + ';\n'
    gw = max(len(g[0]) for g in gates)
    aw = max(len(g[1]) for g in gates) + 6
    bw = max(len(g[2]) for g in gates) + 6
    for name, ia, ib, y in gates:
        out += f'  OR2 {name:<{gw}} (' + f'.A({ia}),'.ljust(aw) + ' ' + f'.B({ib}),'.ljust(bw) + f' .Y({y}));\n'
out += 'endmodule\n'

with open(dst, 'w', newline='\n') as f:
    f.write(out)
print(f'{dst}: {len(addrs)} words')
